"""Bakes a .map (the map editor's format: tools/mapeditor, QM Oct 24) into the game:
src/shared/MapData.luau, which Shared/MapFile decodes into the layout Server/Map builds.

Run: python3 tools/map_bake.py [file.map]     (default maps/world.map)
     copies the file to maps/world.map if it's somewhere else (a download), then writes
     src/shared/MapData.luau. In Studio, the Map Baker plugin's Rebuild button (or its
     Import .map, which skips this step) builds it into workspace.Map.
"""

import json
import os
import shutil
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
WORLD = os.path.join(ROOT, "maps", "world.map")


def mesh_centres():
    """Each world mesh piece's bounding-box centre (studs, from its origin), so the
    builder can place them however Roblox centres an imported mesh."""
    out = {}
    d = os.path.join(ROOT, "assets", "meshes")
    for f in sorted(os.listdir(d)):
        if f.endswith(".obj"):
            v = np.array([list(map(float, l.split()[1:4])) for l in open(os.path.join(d, f)) if l.startswith("v ")])
            out[f[:-4]] = (v.min(0) + v.max(0)) / 2
    return out


def num(v):
    v = round(float(v), 3)
    return str(int(v)) if v == int(v) else ("%.3f" % v).rstrip("0").rstrip(".")


def bake(path=WORLD):
    text = open(path).read()
    data = json.loads(text)
    assert data.get("format") == "StealAndFightPets.map", "not a .map file: " + path
    cols, rows = data["size"]
    assert len(data["rows"]) == rows and all(len(r) == cols for r in data["rows"]), "rows don't match size"
    if os.path.abspath(path) != os.path.abspath(WORLD):
        os.makedirs(os.path.dirname(WORLD), exist_ok=True)
        shutil.copy(path, WORLD)
    level = 1
    while "]" + "=" * level + "]" in text:
        level += 1
    eq = "=" * level
    L = [
        "-- GENERATED by tools/map_bake.py from maps/world.map (the map editor's file): edit the",
        "-- map in tools/mapeditor and bake it again, not this. Shared/MapFile decodes it.",
        "local MapFile = require(script.Parent.MapFile)",
        "local data = MapFile.decode([%s[" % eq + text + "]%s])" % eq,
        "-- each mesh piece's bounding-box centre from its origin (assets/meshes/*.obj)",
        "data.MeshCentres = {",
    ]
    for k, c in mesh_centres().items():
        L.append("\t%s = Vector3.new(%s, %s, %s)," % (k, *(num(v) for v in c)))
    L += ["}", "return data", ""]
    out = os.path.join(ROOT, "src", "shared", "MapData.luau")
    open(out, "w").write("\n".join(L))
    n = sum(1 for o in data["objects"])
    print("baked", os.path.relpath(path, ROOT), "->", os.path.relpath(out, ROOT), "(%dx%d cells, %d objects)" % (cols, rows, n))
    return out


if __name__ == "__main__":
    bake(sys.argv[1] if len(sys.argv) > 1 else WORLD)
