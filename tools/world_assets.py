"""Low-poly world props for Steal And Fight Pets (QM, Oct 23: Archero-style arena):
two pine trees and some stone blocks, as faceted, flat-shaded meshes with studded UVs,
in the knowledge transfer's style (01_terrain_and_meshes.md: convex pieces, one flat
colour per piece, every piece of an item sharing its origin at the base centre, y = 0).

Run: python3 tools/world_assets.py
Writes assets/meshes/<Item>_<Piece>.obj and assets/meshes/pieces.json:
  { item: [ { piece, colour key, obj } ] }
The colour keys are names in Config.WorldColors, so every colour stays tunable in game.

Needs only numpy (the convex hull is a small brute-force one: pieces have < 30 points).
"""

import json
import math
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "assets", "meshes")
STUD = 0.5  # one UV unit = one 0.5-stud stud


def hull(points):
    """Triangles (i, j, k) of the convex hull, wound outward. Brute force: fine for < 40 points."""
    p = np.asarray(points, float)
    n = len(p)
    centre = p.mean(axis=0)
    tris = []
    seen = set()
    for i in range(n):
        for j in range(i + 1, n):
            for k in range(j + 1, n):
                nrm = np.cross(p[j] - p[i], p[k] - p[i])
                length = np.linalg.norm(nrm)
                if length < 1e-9:
                    continue
                nrm /= length
                d = (p - p[i]) @ nrm
                if np.all(d <= 1e-6):
                    tri = (i, j, k)
                elif np.all(d >= -1e-6):
                    tri = (i, k, j)
                    nrm = -nrm
                else:
                    continue
                # coplanar faces: keep one fan per plane by skipping exact duplicates of a plane's points
                key = tuple(sorted((i, j, k)))
                if key in seen:
                    continue
                seen.add(key)
                tris.append(tri)
    # merge coplanar triangles into one set: drop triangles whose plane already has a
    # triangle covering them (keep the non-overlapping fan from the plane's polygon)
    planes = {}
    for t in tris:
        a, b, c = p[list(t)]
        nrm = np.cross(b - a, c - a)
        nrm /= np.linalg.norm(nrm)
        key = (round(nrm[0], 4), round(nrm[1], 4), round(nrm[2], 4), round(float(nrm @ a), 4))
        planes.setdefault(key, set()).update(t)
    out = []
    for key, idx in planes.items():
        nrm = np.array(key[:3])
        idx = list(idx)
        pts = p[idx]
        mid = pts.mean(axis=0)
        # order the plane's points round its centre, then fan
        u = pts[0] - mid
        if np.linalg.norm(u) < 1e-9:
            u = pts[1] - mid
        u /= np.linalg.norm(u)
        v = np.cross(nrm, u)
        ang = np.arctan2((pts - mid) @ v, (pts - mid) @ u)
        order = [idx[i] for i in np.argsort(ang)]
        for m in range(1, len(order) - 1):
            out.append((order[0], order[m], order[m + 1]))
    return out


def stud_axes(n):
    """Fixed in-plane axes for a face normal, so faces on one plane share stud axes."""
    ax = np.abs(n)
    if ax[1] >= ax[0] and ax[1] >= ax[2]:
        return np.array([1, 0, 0]), np.array([0, 0, 1])
    if ax[0] >= ax[2]:
        return np.array([0, 0, 1]), np.array([0, 1, 0])
    return np.array([1, 0, 0]), np.array([0, 1, 0])


def write_obj(path, points):
    p = np.asarray(points, float)
    tris = hull(p)
    lines = ["# generated by tools/world_assets.py"]
    vt, vn, faces = [], [], []
    for v in p:
        lines.append("v %.4f %.4f %.4f" % tuple(v))
    for t in tris:
        a, b, c = p[list(t)]
        n = np.cross(b - a, c - a)
        n /= np.linalg.norm(n)
        vn.append(n)
        su, sv = stud_axes(n)
        ids = []
        for vi in t:
            vt.append(((p[vi] @ su) / STUD, (p[vi] @ sv) / STUD))
            ids.append((vi + 1, len(vt), len(vn)))
        faces.append(ids)
    for uv in vt:
        lines.append("vt %.4f %.4f" % uv)
    for n in vn:
        lines.append("vn %.4f %.4f %.4f" % tuple(n))
    for f in faces:
        lines.append("f " + " ".join("%d/%d/%d" % x for x in f))
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return len(tris)


# ---- shapes -------------------------------------------------------------------------


def prism(rng, y0, y1, r0, r1, sides):
    """A tapering faceted column (a trunk), centred on the y axis."""
    a0 = rng.uniform(0, 2 * math.pi)
    pts = []
    for i in range(sides):
        a = a0 + 2 * math.pi * i / sides
        pts.append((math.cos(a) * r0, y0, math.sin(a) * r0))
        pts.append((math.cos(a) * r1, y1, math.sin(a) * r1))
    return pts


def cone(rng, y0, y1, r, sides, droop):
    """A pine tier: a jittered, drooping rim with a little thickness under it, up to a tip."""
    pts = []
    a0 = rng.uniform(0, 2 * math.pi)
    for i in range(sides):
        a = a0 + 2 * math.pi * i / sides + rng.uniform(-0.18, 0.18)
        rr = r * (1 + rng.uniform(-0.1, 0.1))
        pts.append((math.cos(a) * rr, y0 - droop * rng.uniform(0.5, 1.0), math.sin(a) * rr))
        pts.append((math.cos(a) * rr * 0.6, y0 + 0.35, math.sin(a) * rr * 0.6))
    pts.append((rng.uniform(-0.15, 0.15), y1, rng.uniform(-0.15, 0.15)))
    return pts


def pine(seed, height, tiers, base_r, sides, trunk_r):
    rng = np.random.default_rng(seed)
    pieces = [("Trunk", "PineTrunk", prism(rng, -0.5, height * 0.55, trunk_r, trunk_r * 0.7, 6))]
    start = height * 0.22
    span = height - start
    for t in range(tiers):
        f = t / tiers
        y0 = start + span * f * 0.78
        y1 = min(y0 + span * (0.45 if t < tiers - 1 else 0.55), height)
        r = base_r * (1 - f * 0.62)
        key = "PineNeedles" + "ABCD"[t % 4]
        pieces.append(("Tier%d" % (t + 1), key, cone(rng, y0, y1, r, sides, 0.6)))
    return pieces


def bevelled_block(rng, w, h, d, bevel, wobble):
    """A stone block: a box with every edge chamfered by `bevel`, its top corners nudged a
    little (`wobble`) so it reads hand-cut rather than machined. Base at y = 0."""
    pts = []
    hx, hz = w / 2, d / 2
    for sx in (-1, 1):
        for sz in (-1, 1):
            for sy in (0, 1):
                y = sy * h
                jitter = rng.uniform(-wobble, wobble, 3) if sy == 1 else np.zeros(3)
                # the three points of a chamfered corner
                cy = y - bevel if sy == 1 else y + bevel * 0.4
                pts.append((sx * (hx - bevel) + jitter[0], y + jitter[1] * 0.5, sz * (hz - bevel) + jitter[2]))
                pts.append((sx * hx + jitter[0], cy, sz * (hz - bevel) + jitter[2]))
                pts.append((sx * (hx - bevel) + jitter[0], cy, sz * hz + jitter[2]))
    return pts


def rubble(rng, r, h, sides):
    """A small chunky stone: a jittered polygon with a bevelled top."""
    pts = []
    a0 = rng.uniform(0, 2 * math.pi)
    for i in range(sides):
        a = a0 + 2 * math.pi * i / sides + rng.uniform(-0.25, 0.25)
        rr = r * (1 + rng.uniform(-0.2, 0.2))
        pts.append((math.cos(a) * rr, -0.3, math.sin(a) * rr))
        pts.append((math.cos(a) * rr * 0.98, h * 0.7, math.sin(a) * rr * 0.98))
        pts.append((math.cos(a) * rr * 0.62, h * rng.uniform(0.9, 1.05), math.sin(a) * rr * 0.62))
    return pts


ITEMS = {
    # a tall slim pine and a short wide one
    "PineTall": pine(7, height=16, tiers=4, base_r=4.6, sides=7, trunk_r=0.75),
    "PineShort": pine(23, height=10.5, tiers=3, base_r=4.2, sides=6, trunk_r=0.7),
    # Archero's wall cubes: a full 8-stud block, a half-height one, and loose rubble
    "StoneBlock": [("Block", "Stone", bevelled_block(np.random.default_rng(3), 8, 7, 8, 0.8, 0.12))],
    "StoneBlockLow": [("Block", "Stone", bevelled_block(np.random.default_rng(5), 8, 3.5, 8, 0.7, 0.12))],
    "StoneRubble": [
        ("Big", "StoneDark", rubble(np.random.default_rng(11), 1.6, 1.6, 7)),
        ("Small", "Stone", [(x + 2.2, y, z + 0.9) for x, y, z in rubble(np.random.default_rng(12), 0.9, 1.0, 6)]),
    ],
}


def main():
    os.makedirs(OUT, exist_ok=True)
    index = {}
    for item, pieces in ITEMS.items():
        index[item] = []
        for piece, key, pts in pieces:
            name = "%s_%s" % (item, piece)
            n = write_obj(os.path.join(OUT, name + ".obj"), pts)
            index[item].append({"piece": piece, "colour": key, "obj": name})
            print("%-22s %3d triangles  (%s)" % (name, n, key))
    with open(os.path.join(OUT, "pieces.json"), "w") as fh:
        json.dump(index, fh, indent=2)


if __name__ == "__main__":
    main()
