"""The endgame weapons (QM, Oct 30: recolour some of the drawn weapons into new higher tier
ones, so the ladder reaches the Red Castle and Ocean Trench bosses). Each one is a copy of
a weapon QM drew (src/shared/Weapons/<Base>Model.luau) with its colours swapped, and some
of them turned Neon so they glow (Weapons.flatten leaves Neon parts lit).

Run: python3 tools/weapon_recolors.py [Name ...]
     writes src/shared/Weapons/<Name>Model.luau for each recipe below (all by default).
Then list a new one in Weapons.luau's DRAWN and give it a Config.Weapons entry, and run
tools/render_weapon_icons.py for its icon.
"""

