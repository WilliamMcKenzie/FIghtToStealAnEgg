COLOR = re.compile(r"color = Color3\.fromRGB\((\d+), (\d+), (\d+)\)")


def recolour(name):
    base, swaps, glow = RECIPES[name]
    src = open(os.path.join(DIR, base + "Model.luau")).read()
    body = src[src.index("return {"):]
    out = []
    for line in body.split("\n"):
        m = COLOR.search(line)
        if m and "class =" in line:
            old = "%02x%02x%02x" % tuple(int(x) for x in m.groups())
            new = swaps.get(old, old)
            rgb = ", ".join(str(int(new[i:i + 2], 16)) for i in (0, 2, 4))
            line = line[: m.start()] + "color = Color3.fromRGB(" + rgb + ")" + line[m.end():]
            if new in glow and "neon = true" not in line:
                line = re.sub(r" },?$", lambda e: ", neon = true" + e.group(0), line)
        out.append(line)
    head = (
        f"-- GENERATED by tools/weapon_recolors.py (the {base} recoloured). Don't edit by hand:\n"
        f"-- change its recipe there and run python3 tools/weapon_recolors.py {name}.\n"
        "-- Units are studs, rest pose, facing -Z.\n\n"
    )
    open(os.path.join(DIR, name + "Model.luau"), "w").write(head + "\n".join(out))


if __name__ == "__main__":
    for name in sys.argv[1:] or RECIPES:
        recolour(name)
        print("wrote", name + "Model.luau")
