"""Writes tools/lineup.luau: run it in Studio (Edit) to build the world-asset lineup near
spawn (QM, Oct 23); since Oct 24 it goes to ServerStorage.MovedByMapBaker, out of the map's way. Re-runnable: it deletes what it made before (World and
ServerStorage.WorldAssets) and builds again.

  python3 tools/world_assets.py      # meshes -> assets/meshes/*.obj + pieces.json
  (upload them: assets/meshes/ids.json maps each piece to its rbxassetid)
  python3 tools/make_lineup.py       # -> tools/lineup.luau

What it builds (KT 01_terrain_and_meshes.md floor rules: 8-stud cells, every tile's
bottom at y = -2, a checker Texture tinted with the second shade plus 1-stud studs):
  World.Ground    the grass floor, 1024 x 1024 with a hole for the showcase cells
  World.Showcase  6 x 3 cells just ahead of spawn: grass (top 0), a 2 x 2 dirt patch one
                  stud lower (top -1), and a wall 1 x 2 cells: a dirt block (top 4) under a
                  grass cap 1 stud thick that overhangs it by 1 stud all round
  World.Props     the meshes beside it: PineTall, PineShort, StoneBlock, StoneBlockLow,
                  StoneRubble
  ServerStorage.WorldAssets  one Model per mesh item at the origin, for placing later
Every part and checker Texture carries a ColorKey attribute (Config.WorldColors).
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MESHES = os.path.join(HERE, "..", "assets", "meshes")

PROPS = [  # item, x, z, yaw degrees
    ("StoneRubble", -60, -36, 20),
    ("StoneBlockLow", -48, -36, 0),
    ("StoneBlock", -36, -36, 0),
    ("PineTall", 36, -36, 0),
    ("PineShort", 52, -36, 40),
]

TEMPLATE = r'''-- GENERATED by tools/make_lineup.py: run in Studio's command bar (Edit) to build the
-- world-asset lineup near spawn. Re-runnable.
local AssetService = game:GetService("AssetService")
local ServerStorage = game:GetService("ServerStorage")
-- (a fresh copy of Config: Studio's command bar keeps a required module cached, so
-- colours added since the first run would be missing)
local configCopy = game.ReplicatedStorage.Shared.Config:Clone()
local Config = require(configCopy)
local COLORS = Config.WorldColors
local CHECKER, STUDS = "rbxassetid://84747779882944", "rbxassetid://7447638591"

local ITEMS = --ITEMS--
local PROPS = --PROPS--

-- (the showcase is kept in ServerStorage.MovedByMapBaker, never the workspace: its floor
-- and old props would sit on the map, QM Oct 24; WorldAssets is what the map uses)
local kept = ServerStorage:FindFirstChild("MovedByMapBaker") or Instance.new("Folder")
kept.Name = "MovedByMapBaker"
kept.Parent = ServerStorage
for _, where in { workspace, kept } do
	local old = where:FindFirstChild("World")
	if old then old:Destroy() end
end
local oldAssets = ServerStorage:FindFirstChild("WorldAssets")
if oldAssets then oldAssets:Destroy() end

local world = Instance.new("Folder") world.Name = "World"
local function folder(name, parent)
	local f = Instance.new("Folder") f.Name = name f.Parent = parent return f
end

local ALL = { Enum.NormalId.Top, Enum.NormalId.Front, Enum.NormalId.Back, Enum.NormalId.Left, Enum.NormalId.Right }

local function texture(part, face, image, tile, key, z)
	local t = Instance.new("Texture")
	t.Name = if image == STUDS then "Studs" else "Checker"
	t.Face = face t.Texture = image t.StudsPerTileU = tile t.StudsPerTileV = tile t.ZIndex = z or 1
	if key then t:SetAttribute("ColorKey", key) t.Color3 = COLORS[key] end
	if image == STUDS then t.Transparency = Config.StudTransparency end
	-- (line the texture up with the world grid, whatever the part's corner)
	do
		local corner = part.Position - part.Size / 2
		if face == Enum.NormalId.Top or face == Enum.NormalId.Bottom then
			t.OffsetStudsU, t.OffsetStudsV = corner.X % tile, corner.Z % tile
		elseif face == Enum.NormalId.Front or face == Enum.NormalId.Back then
			t.OffsetStudsU, t.OffsetStudsV = corner.X % tile, corner.Y % tile
		else
			t.OffsetStudsU, t.OffsetStudsV = corner.Z % tile, corner.Y % tile
		end
	end
	t.Parent = part
end

-- a box from (x0, y0, z0) to (x1, y1, z1), coloured `key`. Its top and all four sides
-- wear the same checker and studs at the same scale, lined up with the world grid, so a
-- step's edge or a wall's side reads as the same material as the top (QM, Oct 24).
local function box(name, parent, x0, y0, z0, x1, y1, z1, key)
	local p = Instance.new("Part")
	p.Name = name p.Anchored = true p.Locked = true
	p.Size = Vector3.new(x1 - x0, y1 - y0, z1 - z0)
	p.CFrame = CFrame.new((x0 + x1) / 2, (y0 + y1) / 2, (z0 + z1) / 2)
	p.Material = Enum.Material.SmoothPlastic
	p.TopSurface = Enum.SurfaceType.Smooth p.BottomSurface = Enum.SurfaceType.Smooth
	p:SetAttribute("ColorKey", key) p.Color = COLORS[key]
	for _, face in ALL do
		texture(p, face, CHECKER, 8, key .. "Checker")
		texture(p, face, STUDS, 1, nil, 2)
	end
	p.Parent = parent
	return p
end

-- the floor, around the showcase's cells
local SX0, SX1, SZ0, SZ1 = -24, 24, -48, -24
local ground = folder("Ground", world)
box("Grass", ground, -512, -2, -512, 512, 0, SZ0, "Grass")
box("Grass", ground, -512, -2, SZ1, 512, 0, 512, "Grass")
box("Grass", ground, -512, -2, SZ0, SX0, 0, SZ1, "Grass")
box("Grass", ground, SX1, -2, SZ0, 512, 0, SZ1, "Grass")

-- the showcase: grass cells, a 2 x 2 dirt patch a stud down, a capped wall
local show = folder("Showcase", world)
for col = 0, 5 do
	for row = 0, 2 do
		local x0, z0 = SX0 + col * 8, SZ0 + row * 8
		if (col == 1 or col == 2) and row <= 1 then
			box("Dirt", show, x0, -2, z0, x0 + 8, -1, z0 + 8, "Dirt")
		elseif col == 4 and row <= 1 then
			-- (the wall stands on this cell)
		else
			box("Grass", show, x0, -2, z0, x0 + 8, 0, z0 + 8, "Grass")
		end
	end
end
local wall = Instance.new("Model") wall.Name = "Wall" wall.Parent = show
local WX0, WZ0 = SX0 + 4 * 8, SZ0
box("Dirt", wall, WX0, -2, WZ0, WX0 + 8, 4, WZ0 + 16, "WallDirt")
local LIP = 0.25 -- how far the grass cap overhangs the dirt (QM, Oct 24)
box("Grass", wall, WX0 - LIP, 4, WZ0 - LIP, WX0 + 8 + LIP, 5, WZ0 + 16 + LIP, "Grass")

-- the meshes: templates in ServerStorage.WorldAssets, copies in World.Props
local assets = folder("WorldAssets", ServerStorage)
for item, pieces in ITEMS do
	local model = Instance.new("Model") model.Name = item
	for _, piece in pieces do
		local part = AssetService:CreateMeshPartAsync(Content.fromUri(piece.id), {
			RenderFidelity = Enum.RenderFidelity.Precise,
			CollisionFidelity = Enum.CollisionFidelity.Box,
		})
		part.Name = piece.piece
		part.Anchored = true
		-- (runes and flames glow)
		local glow = piece.colour:match("Rune$") or piece.colour:match("Flame$")
		part.Material = if glow then Enum.Material.Neon else Enum.Material.SmoothPlastic
		part:SetAttribute("ColorKey", piece.colour) part.Color = COLORS[piece.colour]
		-- (pine needles, snow and cactus flowers don't block; trunks, cacti and stones do)
		part.CanCollide = not (piece.piece:match("^Tier") or piece.piece == "Needles" or piece.piece == "Snow" or piece.piece == "Flowers" or piece.piece == "Runes"
			or piece.piece == "Flame" or piece.piece:match("^Fronds") or piece.piece:match("^Blades") or item == "Starfish")
		part.Parent = model
	end
	model.Parent = assets
end
-- (a MeshPart sits at its mesh's own origin: every piece of an item shares the item's
-- base centre, so they all go to the same CFrame)
local props = folder("Props", world)
for _, prop in PROPS do
	local copy = assets[prop[1]]:Clone()
	for _, part in copy:GetChildren() do
		part.CFrame = CFrame.new(prop[2], 0, prop[3]) * CFrame.Angles(0, math.rad(prop[4]), 0)
	end
	copy.Parent = props
end

world.Parent = kept
return "lineup built"
'''


def lua(value, indent=1):
    if isinstance(value, dict):
        inner = "".join("\t" * indent + "%s = %s,\n" % (k, lua(v, indent + 1)) for k, v in value.items())
        return "{\n" + inner + "\t" * (indent - 1) + "}"
    if isinstance(value, (list, tuple)):
        return "{ " + ", ".join(lua(v, indent + 1) for v in value) + " }"
    if isinstance(value, str):
        return '"%s"' % value
    return repr(value)


def main():
    pieces = json.load(open(os.path.join(MESHES, "pieces.json")))
    ids = json.load(open(os.path.join(MESHES, "ids.json")))
    # (only items whose pieces are all uploaded: tools/studio/meshup.py fills ids.json)
    items = {
        item: [{"piece": p["piece"], "colour": p["colour"], "id": ids[p["obj"]]} for p in plist]
        for item, plist in pieces.items()
        if all(p["obj"] in ids for p in plist)
    }
    missing = [item for item in pieces if item not in items]
    if missing:
        print("not uploaded yet (left out):", ", ".join(missing))
    code = TEMPLATE.replace("--ITEMS--", lua(items)).replace("--PROPS--", lua(PROPS))
    with open(os.path.join(HERE, "lineup.luau"), "w") as fh:
        fh.write(code)
    print("wrote tools/lineup.luau")


if __name__ == "__main__":
    main()
