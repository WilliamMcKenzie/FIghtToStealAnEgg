def void_reaver():
    """Void scythe: a long haft and a broad crescent blade sweeping back over it."""
    m = Model()
    shaft(m, -0.8, 4.0, width=0.22)
    m.box(0.28, 0.7, 0, -0.1, WOOD_L, d=0.22)
    m.box(0.28, 0.5, 0, 2.1, WOOD_L, d=0.22)
    m.box(0.3, 0.12, 0, -0.85, GOLD, d=0.24)
    m.diamond(0.24, 0, -1.0, METAL_D, d=0.16)
    # the socket, a gold band, and a short back spike
    m.box(0.36, 0.5, 0, 3.75, METAL_D, d=0.26)
    m.box(0.4, 0.12, 0, 3.55, GOLD, d=0.28)
    m.box(0.4, 0.12, 0, 3.95, GOLD, d=0.28)
    m.bar((0.1, 3.8), (0.6, 4.05), 0.16, METAL_D, d=0.16)
    m.diamond(0.16, 0.6, 4.05, METAL_D, d=0.16)
    # the blade: an arc from the haft's top round to the left, narrowing to a point
    n, a0, a1, r = 14, 30, 200, 1.4
    for i in range(n):
        t0, t1 = i / n, (i + 1) / n
        w = 0.8 + (0.14 - 0.8) * (t0 + t1) / 2
        m.arc(-1.15, 3.0, r, a0 + (a1 - a0) * t0, a0 + (a1 - a0) * t1, 1, w, METAL, d=0.14)
        if i < n - 1:  # (the honed edge, along the inside)
            m.arc(-1.15, 3.0, r - w + 0.12, a0 + (a1 - a0) * t0, a0 + (a1 - a0) * t1, 1, 0.12, METAL_L, d=0.15)
        if i < n - 3:  # (the back)
            m.arc(-1.15, 3.0, r, a0 + (a1 - a0) * t0, a0 + (a1 - a0) * t1, 1, 0.1, METAL_D, d=0.15)
    return m


