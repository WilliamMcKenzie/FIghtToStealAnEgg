# --- bows (string on +X, centred on the grip) ----------------------------------------

def bow_limbs(m, tip_x, tip_y, n, width, color, d=0.2):
    """Both limbs as one arc through the tips, bulging to -X at the grip."""
    r = (tip_x ** 2 + tip_y ** 2) / (2 * tip_x)
    half = math.degrees(math.asin(tip_y / r))
    m.arc(r, 0, r + width / 2, 180 - half, 180 + half, n, width, color, d=d)
    return r


def string(m, x, tip_y):
    m.box(0.07, tip_y * 2, x, 0, STRING, d=0.07)


def starlight_bow():
    """Celestial recurve: wood limbs that flick back at gold tips, a gold star on the grip."""
    m = Model()
    bow_limbs(m, 0.5, 1.85, 14, 0.16, WOOD)
    for side in (-1, 1):
        m.bar((0.5, 1.82 * side), (0.3, 2.25 * side), 0.14, GOLD, d=0.2)
        m.diamond(0.14, 0.3, 2.27 * side, GOLD, d=0.2)
        m.box(0.24, 0.1, 0.42, 1.65 * side, GOLD, d=0.22, rot=-20 * side)
    string(m, 0.5, 1.85)
    m.box(0.22, 0.7, -0.02, 0, WOOD_L, d=0.22)
    m.box(0.36, 0.36, -0.06, 0, GOLD, d=0.26)
    m.diamond(0.36, -0.06, 0, GOLD, d=0.26)
    m.diamond(0.16, -0.06, 0, GOLD_L, d=0.3)
    return m


def galaxy_bow():
    """Cosmic: a great angular bow, steel limbs laid over wood, a gem at the grip."""
    accent = "ff70e0"
    m = Model()
    tip = 2.45
    pts = [(0.0, 0.35), (-0.15, 1.1), (0.1, 1.9), (0.62, tip)]
    for side in (-1, 1):
        p = [(x, y * side) for x, y in pts]
        m.bar((0, 0), p[0], 0.3, WOOD, d=0.22)
        for a, b in zip(p, p[1:]):
            m.bar(a, b, 0.3, WOOD, d=0.2)
            m.bar(a, b, 0.16, METAL, d=0.24)
        for q in p[1:3]:
            m.diamond(0.3, q[0], q[1], METAL_D, d=0.26)
        m.diamond(0.28, 0.62, tip * side, GOLD, d=0.24)
    string(m, 0.62, tip)
    m.box(0.26, 0.8, 0, 0, WOOD_L, d=0.22)
    m.box(0.34, 0.1, 0, 0.42, GOLD, d=0.26)
    m.box(0.34, 0.1, 0, -0.42, GOLD, d=0.26)
    m.diamond(0.24, -0.16, 0, accent, d=0.28, neon=True)
    return m


def eclipse_bow():
    """Void: a smooth dark crescent of steel with a gold ring round the grip, the eclipse."""
