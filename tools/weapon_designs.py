"""The endgame weapons, designed from scratch (QM, Oct 30: "design new weapons instead of
doing reskins"). They replace tools/weapon_recolors.py's recolours of QM's drawings. Each
is built here from boxes in the drawn weapons' blocky style, in their palette only: the
metals, the woods and the gold, plus one accent colour on a staff's gem or a bow's grip.

Units are studs, rest pose, the grip at the origin, pointing up +Y, flat in XY (Z is
thickness), as QM's .bbmodels come out of tools/bbmodel_to_luau.py. Bows are drawn round
their middle, string on +X, like the drawn ones (Weapons.luau's centred() moves them).

Run: python3 tools/weapon_designs.py [Name ...]
     writes src/shared/Weapons/<Name>Model.luau for each design below (all by default).
"""

import math
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
DIR = os.path.join(ROOT, "src", "shared", "Weapons")

# QM's palette, from the drawn weapons
METAL = "9d9d9d"
METAL_D = "676767"
METAL_L = "c9c9c9"
WOOD = "754722"
WOOD_M = "a46422"
WOOD_L = "c7a381"  # (the grip wrap)
GOLD = "eb9d31"
GOLD_L = "f7e26b"
STRING = "f3f3f3"


class Model:
    def __init__(self):
        self.parts = []

    def box(self, w, h, x, y, color, rot=0.0, d=0.2, z=0.0, neon=False, cls="Part"):
        """A w x h box (d thick) centred on (x, y), turned rot degrees round Z."""
        self.parts.append((cls, (w, h, d), (x, y, z), math.radians(rot), color, neon))

    def diamond(self, side, x, y, color, **kw):
        self.box(side, side, x, y, color, rot=45, **kw)

    def bar(self, a, b, width, color, **kw):
        """A box from point a to point b."""
        dx, dy = b[0] - a[0], b[1] - a[1]
        length = math.hypot(dx, dy)
        rot = math.degrees(math.atan2(dy, dx)) - 90
        self.box(width, length, (a[0] + b[0]) / 2, (a[1] + b[1]) / 2, color, rot=rot, **kw)

    def arc(self, cx, cy, r, a0, a1, n, width, color, taper=None, overlap=1.15, **kw):
        """n boxes round a circle from angle a0 to a1 (degrees), width radial, outer edge
        on r. taper=(w0, w1) narrows it along the way."""
        for i in range(n):
            t0, t1 = i / n, (i + 1) / n
            w = width if taper is None else taper[0] + (taper[1] - taper[0]) * (t0 + t1) / 2
            rm = r - w / 2
            a = math.radians(a0 + (a1 - a0) * (t0 + t1) / 2)
            span = math.radians(abs(a1 - a0) / n) * rm * overlap
            self.box(span, w, cx + rm * math.cos(a), cy + rm * math.sin(a), color,
                     rot=math.degrees(a) - 90, **kw)

    def ring(self, cx, cy, r, n, width, color, **kw):
        self.arc(cx, cy, r, 0, 360, n, width, color, **kw)

    def luau(self, name, note):
        def num(v):
            s = "%.4f" % v
            s = s.rstrip("0").rstrip(".")
            return "0" if s in ("-0", "") else s

        rows = []
        for cls, (w, h, d), (x, y, z), a, color, neon in self.parts:
            c, s = math.cos(a), math.sin(a)
            rgb = ", ".join(str(int(color[i:i + 2], 16)) for i in (0, 2, 4))
            cf = ", ".join(num(v) for v in (x, y, z, c, -s, 0, s, c, 0, 0, 0, 1))
            rows.append(
                f'\t\t{{ name = "cube", bone = "weapon", class = "{cls}", size = Vector3.new({num(w)}, {num(h)}, {num(d)}), '
                f"cframe = CFrame.new({cf}), color = Color3.fromRGB({rgb}){', neon = true' if neon else ''} }},"
            )
        return (
            f"-- GENERATED by tools/weapon_designs.py ({note}). Don't edit by hand:\n"
            f"-- change its design there and run python3 tools/weapon_designs.py {name}.\n"
            "-- Units are studs, rest pose, facing -Z.\n\n"
            "return {\n\tbones = {\n"
            '\t\t{ name = "weapon", parent = nil, pivot = Vector3.new(0, 0, 0) },\n'
            "\t},\n\tparts = {\n" + "\n".join(rows) + "\n\t},\n"
            "\t-- keys: { time, x, y, z }; rotation in radians, position in studs, scale as a factor\n"
            "\tanimations = {\n\t},\n}\n"
        )


def grip(m, y0, y1, width=0.24, bands=(), pommel=GOLD):
    """A wrapped grip from y0 to y1 with gold bands at the given heights, and a pommel."""
    m.box(width, y1 - y0, 0, (y0 + y1) / 2, WOOD_L, d=0.22)
    for y in bands:
        m.box(width + 0.08, 0.1, 0, y, GOLD, d=0.26)
    if pommel:
        m.diamond(0.3, 0, y0 - 0.1, pommel, d=0.24)


def shaft(m, y0, y1, width=0.2):
    m.box(width, y1 - y0, 0, (y0 + y1) / 2, WOOD, d=0.2)


