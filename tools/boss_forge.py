"""Boss models written in Python, not Blockbench (QM, Oct 30: new bosses for every biome,
simple and elegant like the Cactus Boss and the Sandworm: few blocks, few bones).

Each boss in tools/boss_designs.py is a Model: its bones, its blocks and its animations.
This writes src/shared/Animals/<Name>Model.luau in exactly the format of
tools/bbmodel_to_luau.py's output (so Rig, Horse and BossView take it as any other), and
tools/render_boss.py draws it without Studio.

  python3 tools/boss_designs.py            # writes every boss's Model.luau
  python3 tools/boss_designs.py Thornback  # just that one

Units are studs at the model's own size, feet on Y = 0, facing -Z (its front). Rotations
are degrees here (X, then Y, then Z: Roblox's CFrame.Angles), radians in the output.

Rules the bosses keep (QM): one bone per thing that really moves (body, head, two or four
legs, a tail, a pair of arms), blocks big and few, the odd wedge for a horn, fin or tooth,
eyes as thin plain plates on the face. Every attack that needs telling apart from the
rest gets its own animation with a `hit` mark (seconds in): the moment it strikes or lets
go. Server/BossAttacks' Anim plays it so the hit lands when the attack does.
"""

import math
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")


def rot(rx=0, ry=0, rz=0):
    """R = Rx * Ry * Rz (CFrame.Angles), degrees in."""
    x, y, z = (math.radians(a) for a in (rx, ry, rz))
    cx, sx, cy, sy, cz, sz = math.cos(x), math.sin(x), math.cos(y), math.sin(y), math.cos(z), math.sin(z)
    Rx = [[1, 0, 0], [0, cx, -sx], [0, sx, cx]]
    Ry = [[cy, 0, sy], [0, 1, 0], [-sy, 0, cy]]
    Rz = [[cz, -sz, 0], [sz, cz, 0], [0, 0, 1]]

    def mul(a, b):
        return [[sum(a[i][k] * b[k][j] for k in range(3)) for j in range(3)] for i in range(3)]

    return mul(mul(Rx, Ry), Rz)


def g(x):
    s = "{:g}".format(round(float(x), 5) + 0.0)
    return "0" if s == "-0" else s


class Model:
    def __init__(self, name, note=""):
        self.name = name
        self.note = note
        self.bones = []  # (name, parent, pivot)
        self.parts = []  # dicts
        self.anims = {}  # name -> { length, hit, tracks: { bone: { rotation, position } } }
        self.sleeping = None  # its Config.BossSleep.Poses entry (sleep())

    # -- shape --------------------------------------------------------------------------
    def bone(self, name, parent, pivot):
        self.bones.append((name, parent, tuple(pivot)))
        return name

    def block(self, name, bone, size, at, color, r=(0, 0, 0), cls="Part", plain=False, neon=False):
        self.parts.append({"name": name, "bone": bone, "class": cls, "size": tuple(size), "at": tuple(at),
                           "r": tuple(r), "color": tuple(color), "plain": plain, "neon": neon})

    def wedge(self, name, bone, size, at, color, r=(0, 0, 0), **kw):
        """A WedgePart: full bottom and back (+Z), sloping up toward its front (-Z)."""
        self.block(name, bone, size, at, color, r, cls="WedgePart", **kw)

    def corner(self, name, bone, size, at, color, r=(0, 0, 0), **kw):
        """A CornerWedgePart: its peak over its (+X, -Z) corner."""
        self.block(name, bone, size, at, color, r, cls="CornerWedgePart", **kw)

    def pair(self, fn, name, bone, size, at, color, r=(0, 0, 0), **kw):
        """The same block on both sides: as given (its L, x < 0) and mirrored across X = 0.
        bone may be "Leg?" style, ? swapped for L and R."""
        x, y, z = at
        rx, ry, rz = r
        fn(name + "L", bone.replace("?", "L"), size, (x, y, z), color, (rx, ry, rz), **kw)
        fn(name + "R", bone.replace("?", "R"), size, (-x, y, z), color, (rx, -ry, -rz), **kw)

    def eyes(self, bone, x, y, z, w, h, color=(30, 22, 34), name="Eye"):
        """Two flat eye plates on a face looking toward -Z (z is the face's front)."""
        for side, sx in (("L", -x), ("R", x)):
            self.block(name + side, bone, (w, h, 0.06), (sx, y, z - 0.03), color, plain=True)

    # -- motion -------------------------------------------------------------------------
    def anim(self, name, length, tracks, hit=None):
        """tracks: { bone: { "r": [(t, rx, ry, rz) degrees], "p": [(t, x, y, z) studs] } }"""
        self.anims[name] = {"length": length, "hit": hit, "tracks": tracks}

    def sleep(self, bones, breathe=None, shut=(), hide=(), note=""):
        """How it sleeps on its dais till you steal its egg (Config.BossSleep.Poses, played by
        Client/BossView): bones and breathe are { bone: (x, y, z, rx, ry, rz) }, studs and
        degrees; shut are its eyes (squashed to a dark line), hide its pupils (gone)."""
        self.sleeping = {"bones": bones, "breathe": breathe or {}, "shut": list(shut), "hide": list(hide), "note": note}

    # -- out ----------------------------------------------------------------------------
    def luau(self):
        pivots = {b[0]: b[2] for b in self.bones}
        out = ["-- GENERATED by tools/boss_forge.py from tools/boss_designs.py (" + self.name + "). Don't edit by",
               "-- hand: change its design there and run python3 tools/boss_designs.py " + self.name + ".",
               "-- Units are studs, rest pose, feet on Y = 0, facing -Z."]
        if self.note:
            out += ["-- " + line for line in self.note.strip().split("\n")]
        out += ["", "return {", "\tbones = {"]
        rests = getattr(self, "rests", {})  # radians, X then Y then Z (a Blockbench drawing's group turns)
        for name, parent, pivot in self.bones:
            rest = rests.get(name, (0, 0, 0))
            out.append('\t\t{{ name = "{}", parent = {}, pivot = Vector3.new({}){} }},'.format(
                name, '"%s"' % parent if parent else "nil", ", ".join(g(v) for v in pivot),
                ", rest = CFrame.Angles({})".format(", ".join(g(v) for v in rest)) if any(rest) else ""))
        out += ["\t},", "\tparts = {"]
        for p in self.parts:
            assert p["bone"] in pivots, self.name + ": " + p["name"] + " on unknown bone " + p["bone"]
            if "cf" in p:  # a part read back from a Blockbench drawing (boss_designs.BLOCKBENCH)
                vals = list(p["cf"])
            else:
                R = rot(*p["r"])
                vals = list(p["at"]) + [R[i][j] for i in range(3) for j in range(3)]
            line = '\t\t{{ name = "{}", bone = "{}", class = "{}", size = Vector3.new({}), cframe = CFrame.new({}), color = Color3.fromRGB({}){}{} }},'.format(
                p["name"], p["bone"], p["class"], ", ".join(g(v) for v in p["size"]), ", ".join(g(v) for v in vals),
                ", ".join(str(int(c)) for c in p["color"]), ", plain = true" if p["plain"] else "",
                ", neon = true" if p["neon"] else "")
            out.append(line)
        out += ["\t},", "\t-- keys: { time, x, y, z }; rotation in radians, position in studs.",
                "\t-- hit: seconds in where an attack strikes (Server/BossAttacks' Anim lands it on the attack)",
                "\tanimations = {"]
        for name in sorted(self.anims, key=lambda n: (["idle", "walk", "gallop"] + [n]).index(n)):
            a = self.anims[name]
            out.append("\t\t{} = {{".format(name))
            out.append("\t\t\tlength = {},".format(g(a["length"])))
            if a["hit"] is not None:
                out.append("\t\t\thit = {},".format(g(a["hit"])))
            out.append("\t\t\ttracks = {")
            for bone, tr in a["tracks"].items():
                assert bone in pivots, self.name + ": animation " + name + " moves unknown bone " + bone
                out.append("\t\t\t\t{} = {{".format(bone))
                for key, field, k in (("r", "rotation", math.pi / 180), ("p", "position", 1)):
                    if key in tr:
                        keys = ", ".join("{{ {}, {}, {}, {} }}".format(g(t), g(x * k), g(y * k), g(z * k)) for t, x, y, z in tr[key])
                        out.append("\t\t\t\t\t{} = {{ smooth = true, keys = {{ {} }} }},".format(field, keys))
                out.append("\t\t\t\t},")
            out.append("\t\t\t},")
            out.append("\t\t},")
        out += ["\t},", "}", ""]
        return "\n".join(out)

    def write(self):
        for need in ("idle", "walk", "gallop"):
            assert need in self.anims, self.name + " has no " + need
        path = os.path.join(ROOT, "src", "shared", "Animals", self.name + "Model.luau")
        open(path, "w").write(self.luau())
        print("wrote", os.path.relpath(path, ROOT), "-", len(self.bones), "bones,", len(self.parts), "blocks")


# -- animation helpers ------------------------------------------------------------------
def wave(length, amp, phase=0.0, steps=8, offset=(0, 0, 0)):
    """A smooth loop: (t, x, y, z) keys of offset + amp * sin(2 pi (t / length + phase))."""
    keys = []
    for i in range(steps + 1):
        t = length * i / steps
        s = math.sin(2 * math.pi * (i / steps + phase))
        keys.append((t, offset[0] + amp[0] * s, offset[1] + amp[1] * s, offset[2] + amp[2] * s))
    return keys


def bob(length, height, phase=0.0, steps=8, double=False):
    """Up and down: 0 at the bottom, height at the top (twice a loop if double, a step each foot)."""
    keys = []
    n = 2 if double else 1
    for i in range(steps + 1):
        t = length * i / steps
        keys.append((t, 0, height * (0.5 - 0.5 * math.cos(2 * math.pi * n * (i / steps + phase))), 0))
    return keys


def poses(*keys):
    """(t, (x, y, z)) pairs to (t, x, y, z) keys."""
    return [(t, *v) for t, v in keys]


SLEEP_BEGIN = "\t\t\t-- the bosses made in Python: written by tools/boss_designs.py from each one's sleep() (QM, Oct 30)"
SLEEP_END = "\t\t\t-- end of the bosses made in Python"


def write_sleep(models):
    """Every model's sleep() into Config.BossSleep.Poses, between two marker comments."""
    path = os.path.join(ROOT, "src", "shared", "Config.luau")
    src = open(path).read()
    if SLEEP_BEGIN in src:
        src = src[:src.index(SLEEP_BEGIN)] + src[src.index(SLEEP_END) + len(SLEEP_END) + 1:]
    start = src.index("{", src.index("Poses = {", src.index("BossSleep = {")))
    depth, i = 0, start
    while True:
        depth += {"{": 1, "}": -1}.get(src[i], 0)
        if depth == 0:
            break
        i += 1
    line = src.rindex("\n", 0, i) + 1

    def pose(v):
        x, y, z, rx, ry, rz = v
        return "{{ {}, {}, {}, {}, {}, {} }}".format(g(x), g(y), g(z), g(math.radians(rx)), g(math.radians(ry)), g(math.radians(rz)))

    out = [SLEEP_BEGIN]
    for m in models:
        s = m.sleeping
        if not s:
            continue
        out.append("\t\t\t{} = {{{}".format(m.name, " -- (" + s["note"] + ")" if s["note"] else ""))
        for key, field in (("bones", "Bones"), ("breathe", "Breathe")):
            out.append("\t\t\t\t{} = {{".format(field))
            for bone, v in s[key].items():
                out.append("\t\t\t\t\t{} = {},".format(bone, pose(v)))
            out.append("\t\t\t\t},")
        for key, field in (("shut", "Shut"), ("hide", "Hide")):
            out.append("\t\t\t\t{} = {{{}}},".format(field, " " + ", ".join('"%s"' % n for n in s[key]) + " " if s[key] else ""))
        out.append("\t\t\t},")
    out.append(SLEEP_END)
    src = src[:line] + "\n".join(out) + "\n" + src[line:]
    open(path, "w").write(src)
    print("wrote", sum(1 for m in models if m.sleeping), "sleep poses into Config.BossSleep.Poses")
